#!/usr/bin/env bash
# One command from a fresh clone to a running store in the "after" (fixed) state:
#   scripts/setup.sh
# Needs Docker (Desktop or Colima) and python3. Takes a few minutes the first time (image build + downloads).
set -euo pipefail
cd "$(dirname "$0")/.."

rand() { python3 -c "import secrets,string;a=string.ascii_letters+string.digits;print(''.join(secrets.choice(a) for _ in range($1)))"; }

if [[ ! -f .env ]]; then
  echo "==> creating .env with random passwords and salts (git-ignored)"
  umask 077
  {
    echo "# Generated by scripts/setup.sh. Never commit this file."
    echo "DB_PASSWORD=$(rand 32)"
    echo "DB_ROOT_PASSWORD=$(rand 32)"
    echo "WP_ADMIN_USER=pp-owner-$(rand 6 | tr 'A-Z' 'a-z')"
    echo "WP_ADMIN_PASSWORD=$(rand 28)"
    for k in AUTH_KEY SECURE_AUTH_KEY LOGGED_IN_KEY NONCE_KEY AUTH_SALT SECURE_AUTH_SALT LOGGED_IN_SALT NONCE_SALT; do
      echo "WP_$k=$(rand 64)"
    done
    echo "STORE_PUBLIC_HOST=shop.kabiirlabs.com"
    echo "# Paste the IDs from Google Tag Manager and GA4 here (they are not secret), then: docker compose up -d"
    echo "GTM_ID="
    echo "GA4_ID="
  } > .env
fi

echo "==> product photos (public-domain, Rijksmuseum via Openverse)"
python3 scripts/fetch-images.py

echo "==> building and starting containers"
docker compose up -d --build --wait

echo "==> installing WordPress, WooCommerce and the demo catalogue"
scripts/wp.sh bash /scripts/install.sh

echo "==> switching to the fixed (after) state"
scripts/state-after.sh

echo
echo "Store ready:   http://127.0.0.1:8081/"
echo "Admin:         http://127.0.0.1:8081/wp-admin/  (user and password in .env)"
echo "Public:        https://\$STORE_PUBLIC_HOST/ once the Cloudflare tunnel routes it to 127.0.0.1:8081"
