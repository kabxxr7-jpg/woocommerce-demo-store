#!/usr/bin/env python3
"""Turn reports/lighthouse/{before,after}/summary.json into reports/SPEED.md (medians of 3 runs)."""
import json, os
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
load = lambda l: json.load(open(os.path.join(root, 'reports', 'lighthouse', l, 'summary.json')))
b, a = load('before'), load('after')
rows = [('performance', 'Performance score', lambda v: f'{v:.0f}'),
        ('lcp', 'Largest Contentful Paint', lambda v: f'{v/1000:.1f} s'),
        ('fcp', 'First Contentful Paint', lambda v: f'{v/1000:.1f} s'),
        ('tbt', 'Total Blocking Time', lambda v: f'{v:.0f} ms'),
        ('cls', 'Cumulative Layout Shift', lambda v: f'{v:.3f}'),
        ('ttfb', 'Server response (TTFB)', lambda v: f'{v:.0f} ms' if v is not None else 'n/a'),
        ('bytes', 'Page weight', lambda v: f'{v/1024/1024:.2f} MB'),
        ('requests', 'Requests', lambda v: f'{v:.0f}')]
out = [f"# Speed: before and after\n\nLighthouse {a['lighthouse'].split('@')[1]}, 3 runs per page and device, **median** shown. "
       f"Measured on {b['base']} (the store's own address on the server, no CDN in between). Mobile uses Lighthouse's default "
       "simulated slow 4G and mid-range phone; desktop uses its desktop preset. Before: "
       f"{b['date'][:16].replace('T', ' ')} UTC; after: {a['date'][:16].replace('T', ' ')} UTC. Raw JSON for every run is in "
       "`reports/lighthouse/` (git keeps the summaries; the per-run JSON is regenerated by `node scripts/lighthouse.mjs`).\n"]
for ff in ('mobile', 'desktop'):
    for page in ('home', 'shop', 'product'):
        k = f'{page}-{ff}'
        mb, ma = b['results'][k]['median'], a['results'][k]['median']
        out.append(f"\n## {page.capitalize()} page, {ff}\n\n| Metric | Before | After |\n|---|---|---|")
        for key, label, fmt in rows:
            out.append(f"| {label} | {fmt(mb[key])} | {fmt(ma[key])} |")
        runs = lambda s: ', '.join(str(r['performance']) for r in s['results'][k]['runs'])
        out.append(f"\nPerformance score of each run: before {runs(b)}; after {runs(a)}.")
open(os.path.join(root, 'reports', 'SPEED.md'), 'w').write('\n'.join(out) + '\n')
print('\n'.join(out))
